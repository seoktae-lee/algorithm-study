// K04-Q2. a=10, b=3 으로 a+b, a-b, a*b, a/b, a%b 를 한 줄에 하나씩 출력하세요
//
// 기대 출력:
// 13
// 7
// 30
// 3
// 1
class Q2 {
    public static void main(String[] args) {
        int a = 10;
        int b = 3;
        System.out.println(a + b);
        System.out.println(a - b);
        System.out.println(a * b);
        System.out.println(a / b);
        System.out.println(a % b);
    }
}
