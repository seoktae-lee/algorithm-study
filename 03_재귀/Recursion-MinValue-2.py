# 8/17 훕코마 - 재귀 알고리즘 최솟값 구하기 2/3
#
# 핵심내용:
# 재귀 호출은 딱 한 번 발생한다.
#
# p = min_value(A, k-1)
#
# 즉 문제 크기가
# n -> n-1 -> n-2 -> n-3 -> ...
# 처럼 한 번에 1씩 감소한다.
#
# 재귀 호출 이후에는
# 현재 값 A[k]와 최솟값 p를 비교하는 작업만 하므로
# 추가 비용은 상수 c이다.
#
# 따라서 점화식은:
# T(n) = T(n-1) + c
#
# 다른 선택지가 아닌 이유:
# T(n/2) -> 문제 크기를 절반으로 줄이지 않음
# 2T(n-1) -> 재귀 호출이 2개가 아님
# +cn -> 한 번의 호출에서 n번 작업하지 않음
#
# 점화식:
# T(n) = T(n-1) + c
