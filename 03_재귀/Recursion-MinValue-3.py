# 8/17 훕코마 - 재귀 알고리즘 최솟값 구하기 3/3
#
# 핵심내용:
# 앞 문제에서 점화식은
#
# T(n) = T(n-1) + c
#
# 이를 풀어보면:
#
# T(n)
# = T(n-1) + c
# = T(n-2) + 2c
# = T(n-3) + 3c
# = ...
# = T(0) + nc
#
# 따라서 총 작업량은 n에 비례한다.
#
# 시간복잡도:
# O(n)
#
# 핵심 사고법:
# 재귀 문제를 만나면
# 1. 재귀 호출이 몇 번 발생하는지
# 2. 문제 크기가 어떻게 줄어드는지
# 3. 한 번의 호출에서 추가 작업이 얼마나 되는지
# 를 확인한다.
#
# 이번 문제:
# 재귀 호출 1개
# 크기 감소: n -> n-1
# 추가 작업: c
# => T(n) = T(n-1) + c
# => O(n)
