# 8/17 훕코마 - 재귀 알고리즘 최솟값 구하기 1/3
#
# 핵심내용:
# p = min_value(A, k-1)는 현재 A[k]를 제외한
# 앞부분의 최솟값을 구해서 p에 저장한다.
#
# 따라서 최종적으로
# p(앞부분의 최솟값)와 A[k](현재 값) 중
# 더 작은 값을 반환하면 된다.
#
# 빈칸:
# (a) A[k] > p
# (b) A[k]
#
# 추가 복습:
# i, j = 0, n-1 은
# i = 0
# j = n-1
# 과 같은 의미이다.
#
# n = 6이면 i = 0, j = 5.
# 파이썬 인덱스는 0부터 시작하므로
# i는 맨 앞, j는 맨 뒤에서 시작한다.

def min_value(A, k):
    if k == 0:
        return A[k]

    p = min_value(A, k - 1)

    if A[k] > p:
        return p

    return A[k]


# 정답:
# (a) A[k] > p
# (b) A[k]
