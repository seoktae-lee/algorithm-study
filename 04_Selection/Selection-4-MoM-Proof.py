# 8/20 훕코마 - Selection Problem 4편
# Median of Medians 수행시간 수학적 분석
#
# 핵심내용:
# MoM의 점화식:
#
# T(n) <= T(n/5) + T(3n/4) + 11n/5
#
# 이 점화식이 O(n)임을 수학적 귀납법으로 증명한다.
#
# 핵심 사고:
# T(n) <= Cn이라는 가정을 넣어서
# n에 비례하는 형태가 유지되는지를 확인한다.
#
# 핵심 플로우:
# 1. 귀납 가정:
#    T(n/5) <= C(n/5)
#    T(3n/4) <= C(3n/4)
#
# 2. 점화식에 대입:
#
# T(n)
# <= C(n/5) + C(3n/4) + 11n/5
#
# = (1/5 + 3/4)Cn + 11n/5
# = (19/20)Cn + 11n/5
#
# 3. T(n) <= Cn이 되려면:
#
# (19/20)C + 11/5 <= C
#
# 1/20 C >= 11/5
#
# C >= 44
#
# 4. 따라서 C >= 44이면:
#    T(n) <= Cn
#
# 결론:
# MoM의 최악 시간복잡도는 O(n)이다.
#
# 핵심 이유:
# 재귀 부분의 크기 비율 합이
#
# 1/5 + 3/4 = 19/20 = 0.95 < 1
#
# 이므로 전체 작업량이 선형 범위 안에서 수렴한다.
#
# 핵심 키워드:
# Recurrence / Induction / C >= 44 / 19/20 < 1 / O(n)
