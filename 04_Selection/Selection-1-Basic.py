# 8/20 훕코마 - Selection Problem 1편
# 기초 선택 문제: 최댓값/최솟값 및 2등 찾기
#
# 핵심내용:
# Selection Problem은 n개의 데이터에서 k번째로 작은/큰 원소를 찾는 문제이다.
# 이때 단순히 답을 찾는 것뿐 아니라 비교 횟수를 줄이는 것이 중요하다.
#
# 상한(Upper Bound):
# 해당 비교 횟수 이내에 항상 해결할 수 있음을 의미한다.
#
# 하한(Lower Bound):
# 최악의 경우에도 최소한 그만큼의 비교가 필요함을 의미한다.
#
# 상한과 하한이 같으면 최적 알고리즘임을 증명할 수 있다.
#
# 상황별 핵심 비교 횟수:
#
# 1. 최댓값 또는 최솟값 하나 찾기
#    -> n - 1회 비교
#
# 2. 최댓값과 최솟값을 동시에 찾기
#    -> 원소를 쌍으로 비교하여 승자/패자 그룹을 나누는 방식
#    -> n이 짝수: 3n/2 - 2
#    -> n이 홀수: 3(n-1)/2
#
# 3. 최솟값과 2번째로 작은 값 찾기
#    -> 토너먼트 트리 사용
#    -> 최솟값과 직접 비교하여 진 원소들만 후보로 남긴다.
#    -> 비교 횟수: n + ceil(log2 n) - 2
#
# 핵심 사고:
# 단순히 전체를 다시 탐색하기보다,
# 이미 수행한 비교 결과를 재사용하면 비교 횟수를 줄일 수 있다.
#
# 핵심 플로우:
# 전체 원소
# -> 비교를 통해 승자/패자 관계 생성
# -> 필요한 후보만 남김
# -> 남은 후보끼리 추가 비교
#
# 핵심 키워드:
# Upper Bound / Lower Bound / Tournament Tree / Comparison Count
