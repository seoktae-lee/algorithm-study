# 핵심내용:
# while문은 n > 0인 동안 반복한다.
#
# n = n - (n & -n)을 통해
# 2진수의 가장 오른쪽 1비트 하나를 제거한다.
#
# 따라서 반복 횟수는 n의 이진 표현에 있는
# 1의 개수이다.
#
# 최악의 경우 1이 비트 전체에 들어 있을 수 있으므로
# 반복 횟수는 비트 수에 비례한다.
#
# n의 비트 수는 log n에 비례하므로
# 최악의 경우 시간복잡도는 O(log n)이다.
#
# 예:
# 11 = 1011
# 1011 -> 1010 -> 1000 -> 0000
# 총 3번 반복
#
# 이번 문제의 정답: O(log n)

def solve(n):
    c = 0

    while n > 0:
        n = n - (n & -n)
        c += 1

    return c


# 시간복잡도: O(log n)
