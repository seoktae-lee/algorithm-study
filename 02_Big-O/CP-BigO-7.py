# 8/13 훕코마 - 복잡도 코드 단답형 5
#
# 문제:
# f([4, 2, 1, 3, 6, 5], 6)의 반환값과 시간복잡도를 구한다.
#
# 핵심내용:
# i, j = 0, n - 1 은 다음과 같은 뜻이다.
# i = 0
# j = n - 1
#
# n = 6이면 i = 0, j = 5이다.
# 배열의 인덱스는 0부터 시작하므로 i는 맨 앞,
# j는 맨 뒤에서 시작한다.
#
# while 반복마다 i 또는 j가 가운데 방향으로 한 칸 이상 이동한다.
# 따라서 전체 반복 횟수는 n에 비례한다.
# 중첩된 반복문이 아니므로 시간복잡도는 O(n)이다.

def f(A, n):
    s = 0
    i, j = 0, n - 1

    while i < j:
        if A[i] < A[j]:
            s += A[j] - A[i]
            j -= 1
        elif A[i] > A[j]:
            s += A[i] - A[j]
            i += 1
        else:
            i += 1
            j -= 1

    return s


# f([4, 2, 1, 3, 6, 5], 6) = 6
# 시간복잡도: O(n)
