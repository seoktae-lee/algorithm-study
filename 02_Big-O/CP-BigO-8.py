# 8/13 훕코마 - Big-O 크기 순으로 나열
#
# 핵심내용:
# 이 문제는 n이 매우 커졌을 때
# 어떤 식이 더 빠르게 증가하는지를 비교하는 문제이다.
#
# 여러 항이 +, -로 연결되어 있으면
# 가장 빠르게 증가하는 항만 남긴다.
# 계수와 낮은 차수 항은 Big-O에서 무시한다.
#
# 핵심 성장 순서:
# log n
# < (log n)^k
# < n^a
# < c^n
# < n!
#
# 여기서 k > 0, a > 0인 경우이다.
#
# 특히:
# log^100 n = (log n)^100
#
# 위의 100은 로그의 밑이 아니라
# 'log n 전체를 100제곱'한다는 뜻이다.
#
# 그리고 아무리 로그를 높은 거듭제곱해도
# 결국 n의 양의 거듭제곱보다 느리게 성장한다.
#
# 예:
# (log n)^100 < sqrt(n)   (충분히 큰 n에서)
#
#
# 각 식:
#
# 1. 2n^2 - 10n + 2^9 log n
#    -> n^2가 가장 빠르게 증가
#    -> O(n^2)
#
# 2. 4^(log_4 n)
#    -> 밑이 같은 지수와 로그는 서로 없어짐
#    -> 4^(log_4 n) = n
#    -> O(n)
#
# 3. 9n log^2 n + n^1.2
#    -> n log^2 n보다 n^1.2가 더 빠르게 증가
#    -> O(n^1.2)
#
# 4. sqrt(n log n) + log^100 n
#    -> sqrt(n log n)는 n의 양의 거듭제곱 성분을 포함
#    -> (log n)^100보다 결국 더 빠르게 증가
#    -> O(sqrt(n log n))
#
# 5. (n/2)!
#    -> 팩토리얼은 다항식보다 훨씬 빠르게 증가
#
# 따라서 작은 것부터:
# 4 < 2 < 3 < 1 < 5
#
# 정답: 4 2 3 1 5
