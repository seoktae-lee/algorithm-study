# 8/13 훕코마 - 코드 분석 (1) 1/2
#
# 핵심내용:
# A.pop(0)는 리스트의 맨 앞 원소를 제거한다.
#
# 맨 앞 원소를 제거하면 뒤에 있는 원소들을
# 한 칸씩 앞으로 이동해야 하므로 O(n)이다.
#
# while은 리스트의 원소를 하나씩 제거하므로 n번 반복한다.
#
# 주의:
# while만 보면 O(n)처럼 보이지만
# 반복문 내부의 pop(0)가 O(n)이므로
#
# O(n) x O(n) = O(n^2)
#
# 이 된다.
#
# pop(0) -> O(n)
# pop()   -> O(1)
#
# 실행 결과:
# x가 1, 2, 3, 4, 5 순서로 꺼내진다.
# x % 2가 참인 홀수만 s에 더한다.
#
# 1 + 3 + 5 = 9

def solve(A):
    n = len(A)
    s = 0

    while len(A) > 0:
        x = A.pop(0)

        if x % 2:
            s += x

    return s


A = [1, 2, 3, 4, 5]

# 출력: 9
# 시간복잡도: O(n^2)
