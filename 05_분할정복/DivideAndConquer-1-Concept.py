# [2026-08-24] 훕코마 - 분할정복(Divide & Conquer)
# 동영상 1편: 알고리즘 분할정복방법 소개
#
# 핵심내용:
# 거대한 문제를 한 번에 풀려 하지 않고, 문제가 충분히 작아질 때까지
# 비슷한 형태의 작은 부분 문제로 나누어(Divide) 해결(Conquer)한 뒤
# 이를 결합(Combine)하여 원래 문제의 답을 구하는 기본 알고리즘 전략이다.
#
# 핵심 개념:
# 1. 분할 (Divide): 문제를 동일한 구조의 작은 부분 문제들로 쪼갬
# 2. 정복 (Conquer): 기저 상태(Base Case)에 도달하면 직접 해결
# 3. 결합 (Combine): 작은 문제들의 해를 모아 전체 문제의 해 도출
# 4. 거듭제곱 최적화: a^n을 a^(n/2) * a^(n/2)로 쪼개어 부분 문제 해를 재사용
#
# 접근법:
# 1. 문제 크기가 충분히 작을 때(n=0 또는 n=1) 반환할 Base Case 정의
# 2. n이 짝수일 때: a^(n/2)를 구한 뒤 제곱 (x * x)
# 3. n이 홀수일 때: a^(n/2)를 구한 뒤 제곱하고 a를 한 번 더 곱함 (x * x * a)
#
# 핵심 사고:
# 동일한 계산 결과를 매번 재귀 호출하지 않고 한 번 계산한 값(x)을 저장하여
# 재사용함으로써 재귀 호출 횟수를 절반씩 줄이는 효율성을 확보한다.
#
# 핵심 플로우:
# Base Case 체크 -> n/2 크기의 부분 문제 1회 호출 -> 결과 x 저장 -> 짝/홀 조건에 맞춰 x*x (+a) 반환
#
# 핵심 키워드:
# Divide and Conquer / Base Case / Power Optimization / O(log N) / Exponentiation

def power(a, n):
    # Base Case: a^0 = 1
    if n == 0:
        return 1
    
    # n/2 크기의 부분 문제를 단 1회만 재귀 호출하여 결과 재사용
    x = power(a, n // 2)
    
    # 짝수인 경우: (a^(n/2))^2
    if n % 2 == 0:
        return x * x
    # 홀수인 경우: (a^(n/2))^2 * a
    else:
        return x * x * a

# 예시 실행
print(power(2, 10))  # 1024
