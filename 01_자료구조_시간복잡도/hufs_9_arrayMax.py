
# 문제: 기본연산횟수 - arrayMax
#
# 입력:
# A = [4, 1, 5, 3, 9, 10, 8]
# n = 7
#
# 조건:
# return 문 자체와 for 문의 반복을 제어하는 부분의
# 기본연산은 무시한다.
#
# 기본연산:
# currentMax = A[0] → 1회
# if 비교 → n-1회
# currentMax = A[i] → 최악의 경우 n-1회
#
# 총 기본연산횟수:
# 1 + (n-1) + (n-1)
# = 2n - 1
#
# n = 7이므로:
# 2 × 7 - 1 = 13
#
# 정답: 13
# 일반식: 2n - 1
# 시간복잡도: O(n)

